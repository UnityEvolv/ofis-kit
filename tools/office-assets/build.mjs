#!/usr/bin/env node
/**
 * Build each theme's symbol bundle and catalog from its per-symbol files.
 *
 * The source of a theme is `assets/<view>/<theme>/symbols/<mode>/<id>.svg`: one
 * standalone SVG per symbol, which previews on its own in a file browser, on
 * GitHub or in Figma. This script assembles them into `symbols-<mode>.svg` (the
 * `<defs>` block the prompt and the examples copy) and writes `CATALOG.md`, a
 * gallery of every symbol in light and dark. A test fails when a bundle or a
 * catalog is stale, so the split files are the only thing anyone edits.
 *
 *   node tools/office-assets/build.mjs          write bundles and catalogs
 *   node tools/office-assets/build.mjs --check  exit 1 if any is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { parseXml, referencedIds } from './xml.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const ASSETS = join(ROOT, 'assets')

export const MODES = ['light', 'dark']
export const VIEWS = { cut: 'cutaway', top: 'top-down' }
const LABELS = { modern: 'Modern office', underwater: 'Underwater', galaxy: 'Galaxy' }

/** Every `assets/<view>/<theme>/` folder. */
export function listLibraries() {
  const found = []
  for (const view of Object.keys(VIEWS)) {
    const dir = join(ASSETS, view)
    if (!existsSync(dir)) continue
    for (const theme of readdirSync(dir).sort()) {
      const themeDir = join(dir, theme)
      if (
        existsSync(join(themeDir, 'symbols')) ||
        existsSync(join(themeDir, 'symbols-light.svg'))
      ) {
        found.push({ view, theme, dir: themeDir, label: LABELS[theme] ?? theme })
      }
    }
  }
  return found
}

/** One split file, read: its symbol element, its defs, its measured box. */
function readSymbolFile(file) {
  const source = readFileSync(file, 'utf8')
  const root = parseXml(source)
  const text = (element) => source.slice(element.start, element.end)
  const defs = root.children.find((child) => child.name === 'defs')
  const symbol = root.children.find((child) => child.name === 'g')
  const id = root.attributes['data-symbol'] ?? symbol?.attributes['id']
  const bbox = (root.attributes['data-bbox'] ?? '').split(' ').map(Number)
  return {
    id,
    bbox: bbox.length === 4 && bbox.every(Number.isFinite) ? bbox : null,
    defs:
      defs === undefined
        ? []
        : defs.children.map((child) => ({ id: child.attributes['id'], text: text(child) })),
    symbol: symbol === undefined ? null : text(symbol),
    source,
  }
}

/** The ids a split file defines and the ids it references, for the self-contained check. */
export function checkSelfContained(file) {
  const source = readFileSync(file, 'utf8')
  const defined = new Set([...source.matchAll(/\sid="([^"]+)"/g)].map((match) => match[1]))
  const missing = [...referencedIds(source)].filter((id) => !defined.has(id))
  return missing
}

/** Assemble one mode's bundle text from its split files. */
export function buildBundle(library, mode) {
  const dir = join(library.dir, 'symbols', mode)
  if (!existsSync(dir)) return null
  const files = readdirSync(dir)
    .filter((name) => name.endsWith('.svg'))
    .sort()
  const defs = []
  const seen = new Set()
  const push = (id, text) => {
    if (id !== undefined && seen.has(id)) return
    if (id !== undefined) seen.add(id)
    defs.push(text)
  }

  // Theme-wide paints first, so wall swatches and the sky keep their place at
  // the top of the block the way the hand-written bundles had them.
  const theme = files.find((name) => name === '_theme.svg')
  if (theme !== undefined) {
    const entry = readSymbolFile(join(dir, theme))
    for (const def of entry.defs) push(def.id, def.text)
  }

  const symbols = []
  for (const name of files) {
    if (name.startsWith('_')) continue
    const entry = readSymbolFile(join(dir, name))
    if (entry.symbol === null) throw new Error(`${join(dir, name)} has no <g> symbol`)
    for (const def of entry.defs) push(def.id, def.text)
    symbols.push({ id: entry.id, text: entry.symbol, bbox: entry.bbox })
  }
  for (const symbol of symbols) push(symbol.id, symbol.text)

  const lines = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" data-ofis-symbols="${library.view}/${library.theme}" data-mode="${mode}">`,
    `  <!-- Generated by tools/office-assets/build.mjs from symbols/${mode}/*.svg. Do not edit; edit the symbol files and run npm run office:assets. -->`,
    '  <defs>',
    ...defs.map((text) => `    ${text}`),
    '  </defs>',
    '</svg>',
    '',
  ]
  return { text: lines.join('\n'), symbols }
}

/** The catalog page: every symbol, light and dark, with its measured size. */
export function buildCatalog(library, symbolsByMode) {
  const light = symbolsByMode.light ?? []
  const dark = new Set((symbolsByMode.dark ?? []).map((symbol) => symbol.id))
  const rows = light.map((symbol) => {
    const size =
      symbol.bbox === null ? '' : `${Math.round(symbol.bbox[2])} × ${Math.round(symbol.bbox[3])}`
    const darkCell = dark.has(symbol.id)
      ? `<img src="symbols/dark/${symbol.id}.svg" alt="${symbol.id}, dark" height="64">`
      : '—'
    return `| \`${symbol.id}\` | <img src="symbols/light/${symbol.id}.svg" alt="${symbol.id}, light" height="64"> | ${darkCell} | ${size} |`
  })
  return [
    `# ${library.label} symbols, ${VIEWS[library.view]}`,
    '',
    '<!-- Generated by tools/office-assets/build.mjs. Do not edit; edit the files under symbols/ and run npm run office:assets. -->',
    '',
    `One file per symbol under \`symbols/light/\` and \`symbols/dark/\`; each previews on its own and carries the paints it uses. Sizes are the drawn box in viewBox pixels. The bundles \`symbols-light.svg\` and \`symbols-dark.svg\` are generated from these files.`,
    '',
    '| Symbol | Light | Dark | Size |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n')
}

export function buildAll() {
  const out = {}
  for (const library of listLibraries()) {
    const symbolsByMode = {}
    for (const mode of MODES) {
      const built = buildBundle(library, mode)
      if (built === null) continue
      out[join(library.dir, `symbols-${mode}.svg`)] = built.text
      symbolsByMode[mode] = built.symbols
    }
    if (Object.keys(symbolsByMode).length > 0) {
      out[join(library.dir, 'CATALOG.md')] = buildCatalog(library, symbolsByMode)
    }
  }
  return out
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const [file, content] of Object.entries(buildAll())) {
    if (check) {
      const current = existsSync(file) ? readFileSync(file, 'utf8') : null
      if (current !== content) {
        stale += 1
        console.error(`stale: ${file} — run npm run office:assets`)
      }
    } else {
      writeFileSync(file, content)
      console.log(`wrote ${file}`)
    }
  }
  if (check && stale > 0) process.exit(1)
}
